AD.addLesson({
  id: 'context-sessions',
  n: 6,
  title: 'Interrupt, compact & resume',
  blurb: 'Stop Claude mid-task, save context and continue tomorrow.',
  icon: '↺',
  pro: true,
  summary: 'You interrupted Claude, redirected it, compacted context and resumed a session.',
  start: 'claude',
  steps: [
    {
      say: `<p>Let's give Claude a big task. Ask it to <code>convert the app to TypeScript</code>.</p>`,
      match: (v) => !v.startsWith('/') && /(typescript|\bts\b)/i.test(v),
      answer: 'convert the app to TypeScript',
      hint: 'Ask Claude to convert the app to **TypeScript**.',
      successTitle: 'Here we go…',
      success: '',
      respond: [{ think: 600 }],
      xp: 5,
      pause: false,
    },
    {
      say: `<p>Hmm – Claude is about to rewrite <b>every file</b>. That's more than you wanted.</p><p>Press <b>Esc</b> to interrupt it right now.</p>`,
      during: [
        { tool: 'Search', arg: 'pattern: "**/*.js"', out: 'Found 7 files', delay: 300 },
        { text: "I'll convert all 7 files to TypeScript, add a tsconfig.json and update the build.", delay: 300 },
        { tool: 'Write', arg: 'tsconfig.json', out: 'Wrote 12 lines to tsconfig.json' },
        { think: Infinity, label: 'Converting' },
      ],
      success: 'Esc stops Claude immediately. Nothing more is changed.',
      respond: [{ out: 'Interrupted by user' }],
    },
    {
      say: `<p>Now steer it. Tell Claude to <b>only convert <code>src/utils.js</code></b> for now.</p>`,
      match: (v) => !v.startsWith('/') && /utils/i.test(v),
      answer: 'only convert src/utils.js for now',
      hint: 'Mention **utils** – e.g. `only convert src/utils.js for now`.',
      success: 'Interrupt + redirect is one of the most useful habits in Claude Code.',
      respond: [
        { think: 700 },
        { tool: 'Write', arg: 'src/utils.ts', out: 'Wrote 46 lines to src/utils.ts' },
        { text: 'Converted only `src/utils.js` → `src/utils.ts` with types for all three helpers.' },
      ],
    },
    {
      say: `<p>After a long session the context fills up. <code>/compact</code> replaces the conversation with a short summary, so you can keep going.</p><p>Run <code>/compact</code>.</p>`,
      match: /^\/compact(\s.*)?$/,
      answer: '/compact',
      hints: [
        { match: /^\/clear$/, msg: '`/clear` would forget everything. `/compact` keeps a summary.' },
        { match: /^compact$/i, msg: 'Add the slash: `/compact`.' },
      ],
      hint: 'Type `/compact`.',
      success: 'Tip: `/compact focus on the TypeScript work` tells it what to keep.',
      respond: [
        { think: 1000, label: 'Compacting conversation' },
        { out: 'Compacted. ctrl+o to see full summary' },
      ],
    },
    {
      say: `<p>Time to stop for the day. Exit Claude Code.</p>`,
      match: /^\/(exit|quit)$/,
      answer: '/exit',
      hints: [{ match: /^(exit|quit)$/i, msg: 'Inside Claude Code: `/exit`.' }],
      hint: 'Use `/exit`.',
      success: '',
      respond: [{ exit: true }],
      xp: 5,
    },
    {
      say: `<p>Next morning you want to pick up <b>exactly where you left off</b>.</p><p>Start Claude with the flag that continues your most recent conversation: <code>claude --continue</code></p>`,
      match: /^claude\s+(--continue|-c)$/,
      answer: 'claude --continue',
      hints: [
        { match: /^claude$/, msg: 'That starts a **new** session. Add a flag to continue the last one.' },
        { match: /^claude\s+(--resume|-r)$/, msg: '`--resume` opens a list to pick from. To jump straight into the latest one, use `--continue`.' },
        { match: /^claude\s+continue$/, msg: 'Flags start with two dashes: `--continue`.' },
      ],
      hint: 'Type `claude --continue` (or the short form `claude -c`).',
      success: 'Short form: `claude -c`. Use `claude --resume` to pick an older session.',
      respond: [
        { launch: true, note: '  Continuing previous conversation…' },
        { text: 'Welcome back! Last time I converted `src/utils.js` to TypeScript. Shall I continue with `src/storage.js`?' },
      ],
    },
  ],
});
